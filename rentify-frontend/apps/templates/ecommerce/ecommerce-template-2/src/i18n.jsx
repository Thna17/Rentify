export const dictionaries = { en, kh: km };

const lookup = (dictionary, key) =>
  key.split('.').reduce((node, part) => (node && typeof node === 'object' ? node[part] : undefined), dictionary);

export const translate = (language, key, params = {}) => {
  // English singular forms live next to the plural as `<key>One`; Khmer has no plural inflection.
  const singular = params.count === 1 ? lookup(dictionaries[language], `${key}One`) : undefined;
  const value = singular ?? lookup(dictionaries[language], key) ?? lookup(en, key);
  if (typeof value !== 'string') return params.defaultValue ?? key;
  return value.replace(/\{\{(\w+)\}\}/g, (match, name) => (name in params ? String(params[name]) : match));
};

const readStoredLanguage = () => {
  try {
    const stored = window.localStorage.getItem(STORAGE_KEY);
    return LANGUAGES.some((language) => language.code === stored) ? stored : 'en';
  } catch {
    return 'en';
  }
};

const I18nContext = createContext({
  language: 'en',
  setLanguage: () => undefined,
  t: (key, params) => translate('en', key, params),
});

export function I18nProvider({ children, initialLanguage }) {
  const [language, setLanguageState] = useState(() => initialLanguage || readStoredLanguage());

  const setLanguage = useCallback((code) => {
    if (!LANGUAGES.some((item) => item.code === code)) return;
    setLanguageState(code);
    try {
      window.localStorage.setItem(STORAGE_KEY, code);
    } catch {
      // Storage can be unavailable (private mode); the choice still applies for this visit.
    }
  }, []);

  useEffect(() => {
    const htmlLang = LANGUAGES.find((item) => item.code === language)?.htmlLang || 'en';
    document.documentElement.lang = htmlLang;
  }, [language]);

  const value = useMemo(
    () => ({ language, setLanguage, t: (key, params) => translate(language, key, params) }),
    [language, setLanguage]
  );
  return <I18nContext.Provider value={value}>{children}</I18nContext.Provider>;
}

export const useI18n = () => useContext(I18nContext);
