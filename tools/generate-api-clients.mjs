// Helper to convert OpenAPI schema to TypeScript representation
function schemaToTs(schema, namespace, indent = '') {
  if (!schema) return 'any';

  if (schema.$ref) {
    const rawName = schema.$ref.replace('#/components/schemas/', '');
    return `${namespace}.${rawName}`;
  }

  if (schema.oneOf) {
    const parts = schema.oneOf.map((s) => schemaToTs(s, namespace, indent));
    return `(${parts.join(' | ')})`;
  }

  if (schema.anyOf) {
    const parts = schema.anyOf.map((s) => schemaToTs(s, namespace, indent));
    return `(${parts.join(' | ')})`;
  }

  if (schema.allOf) {
    const parts = schema.allOf.map((s) => schemaToTs(s, namespace, indent));
    return `(${parts.join(' & ')})`;
  }

  if (schema.enum) {
    return schema.enum.map((v) => JSON.stringify(v)).join(' | ');
  }

  if (schema.type === 'string') {
    return 'string';
  }

  if (schema.type === 'number' || schema.type === 'integer') {
    return 'number';
  }

  if (schema.type === 'boolean') {
    return 'boolean';
  }

  if (schema.type === 'array') {
    return `Array<${schemaToTs(schema.items, namespace, indent)}>`;
  }

  if (schema.type === 'object' || schema.properties) {
    if (!schema.properties && schema.additionalProperties) {
      if (typeof schema.additionalProperties === 'object') {
        return `Record<string, ${schemaToTs(schema.additionalProperties, namespace, indent)}>`;
      }
      return 'Record<string, any>';
    }

    if (!schema.properties) return 'Record<string, any>';

    const lines = ['{'];
    const required = new Set(schema.required || []);
    const sortedProps = Object.keys(schema.properties).sort();

    for (const key of sortedProps) {
      const prop = schema.properties[key];
      const opt = required.has(key) ? '' : '?';
      const cleanKey = /^[a-zA-Z_$][a-zA-Z0-9_$]*$/.test(key) ? key : JSON.stringify(key);
      const isNull = prop.nullable ? ' | null' : '';
      const doc = prop.description ? `  ${indent}/** ${prop.description.replace(/\*\//g, '* /')} */\n` : '';
      lines.push(`${doc}  ${indent}${cleanKey}${opt}: ${schemaToTs(prop, namespace, indent + '  ')}${isNull};`);
    }
    lines.push(indent + '}');
    return lines.join('\n');
  }

  return 'any';
}

function generateTypesForDoc(doc, namespace) {
  const schemas = doc.components?.schemas || {};
  const schemaNames = Object.keys(schemas).sort();

  const codeLines = [
    HEADER,
    `export namespace ${namespace} {`,
  ];

  for (const name of schemaNames) {
    const schema = schemas[name];
    const doc = schema.description ? `  /** ${schema.description.replace(/\*\//g, '* /')} */\n` : '';

    if (schema.type === 'string' && schema.enum) {
      const enumValues = schema.enum.map((v) => JSON.stringify(v)).join(' | ');
      codeLines.push(`${doc}  export type ${name} = ${enumValues};`);
    } else if (schema.$ref) {
      const refName = schema.$ref.replace('#/components/schemas/', '');
      codeLines.push(`${doc}  export type ${name} = ${refName};`);
    } else if (schema.oneOf) {
      const parts = schema.oneOf.map((s) => schemaToTs(s, namespace, '  '));
      codeLines.push(`${doc}  export type ${name} = ${parts.join(' | ')};`);
    } else if (schema.type === 'object' || schema.properties) {
      codeLines.push(`${doc}  export interface ${name} ${schemaToTs(schema, namespace, '  ')}`);
    } else {
      codeLines.push(`${doc}  export type ${name} = ${schemaToTs(schema, namespace, '  ')};`);
    }
    codeLines.push('');
  }

  // Operations map
  codeLines.push(`  export interface Operations {`);

  const paths = Object.keys(doc.paths || {}).sort();
  for (const pathKey of paths) {
    const pathObj = doc.paths[pathKey];
    const methods = Object.keys(pathObj).sort();

    for (const method of methods) {
      if (!['get', 'post', 'put', 'patch', 'delete'].includes(method)) continue;
      const op = pathObj[method];
      if (!op.operationId) continue;

      const pathParams = (op.parameters || []).filter((p) => p.in === 'path');
      const queryParams = (op.parameters || []).filter((p) => p.in === 'query');

      const s2xx = op.responses['200'] || op.responses['201'] || op.responses['204'];
      const resSchema = s2xx?.content?.['application/json']?.schema;
      const resType = resSchema ? schemaToTs(resSchema, namespace, '      ') : (op.responses['204'] ? 'void' : 'any');

      const reqBodySchema = op.requestBody?.content?.['application/json']?.schema;
      const reqBodyType = reqBodySchema ? schemaToTs(reqBodySchema, namespace, '      ') : null;

      codeLines.push(`    ${op.operationId}: {`);
      codeLines.push(`      method: '${method.toUpperCase()}';`);
      codeLines.push(`      path: '${pathKey}';`);
      codeLines.push(`      parameters: {`);
      if (pathParams.length > 0) {
        codeLines.push(`        path: {`);
        for (const p of pathParams.sort((a, b) => a.name.localeCompare(b.name))) {
          const opt = p.required ? '' : '?';
          codeLines.push(`          ${p.name}${opt}: ${p.schema?.type === 'number' || p.schema?.type === 'integer' ? 'number' : 'string'};`);
        }
        codeLines.push(`        };`);
      }
      if (queryParams.length > 0) {
        codeLines.push(`        query?: {`);
        for (const p of queryParams.sort((a, b) => a.name.localeCompare(b.name))) {
          const opt = p.required ? '' : '?';
          codeLines.push(`          ${p.name}${opt}: ${schemaToTs(p.schema, namespace, '          ')};`);
        }
        codeLines.push(`        };`);
      }
      codeLines.push(`      };`);
      if (reqBodyType) {
        const bodyOpt = op.requestBody?.required ? '' : '?';
        codeLines.push(`      body${bodyOpt}: ${reqBodyType};`);
      }
      codeLines.push(`      response: ${resType};`);
      codeLines.push(`    };`);
    }
  }

  codeLines.push(`  }`);
  codeLines.push(`}`);
  codeLines.push('');

  // Export individually prefixed aliases to guarantee zero collision in global scope
  for (const name of schemaNames) {
    codeLines.push(`export type ${namespace}${name} = ${namespace}.${name};`);
  }
  codeLines.push('');

  return codeLines.join('\n');
}

