const { DataTypes } = require('sequelize');
const sequelize = require('../config/db');

module.exports = sequelize.define('SupportCase', {
  id: { type: DataTypes.UUID, primaryKey: true, defaultValue: DataTypes.UUIDV4 },
  caseNumber: { type: DataTypes.STRING(32), allowNull: false, unique: true },
  caseType: { type: DataTypes.STRING(64), allowNull: false },
  priority: { type: DataTypes.STRING(24), allowNull: false },
  status: { type: DataTypes.STRING(32), allowNull: false, defaultValue: 'open' },
  queueKey: { type: DataTypes.STRING(64), allowNull: true },
  requesterSubjectId: { type: DataTypes.STRING(128), allowNull: true },
  requesterKind: { type: DataTypes.STRING(32), allowNull: false },
  storeId: { type: DataTypes.UUID, allowNull: true },
  assigneeSubjectId: { type: DataTypes.UUID, allowNull: true },
  sourceSystem: { type: DataTypes.STRING(32), allowNull: true },
  sourceType: { type: DataTypes.STRING(64), allowNull: true },
  sourceId: { type: DataTypes.STRING(128), allowNull: true },
  activeSourceKey: { type: DataTypes.STRING(64), allowNull: true, unique: true },
  summary: { type: DataTypes.STRING(500), allowNull: false },
  descriptionClassification: { type: DataTypes.STRING(64), allowNull: true },
  language: { type: DataTypes.STRING(16), allowNull: true },
  policyVersion: { type: DataTypes.STRING(64), allowNull: true },
  openedAt: { type: DataTypes.DATE, allowNull: false },
  triagedAt: { type: DataTypes.DATE, allowNull: true },
  serviceDeadlineAt: { type: DataTypes.DATE, allowNull: true },
  deadlinePausedAt: { type: DataTypes.DATE, allowNull: true },
  deadlinePauseReason: { type: DataTypes.STRING(128), allowNull: true },
  escalatedAt: { type: DataTypes.DATE, allowNull: true },
  resolvedAt: { type: DataTypes.DATE, allowNull: true },
  closedAt: { type: DataTypes.DATE, allowNull: true },
  resolutionCode: { type: DataTypes.STRING(64), allowNull: true },
  resolutionSummary: { type: DataTypes.STRING(1000), allowNull: true },
  version: { type: DataTypes.INTEGER, allowNull: false, defaultValue: 1 },
}, { timestamps: true, indexes: [{ fields: ['storeId', 'createdAt', 'id'] }, { fields: ['status', 'queueKey'] }] });
